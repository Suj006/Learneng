"""IPA + syllables for PING VIBE's published words from the CMU Pronouncing Dictionary (US English) and pyphen (en_GB)
hyphenation. Nothing is invented: words missing from CMU get no IPA. Output: src/server/content/pronunciation.ts"""
import json, cmudict, pyphen
CMU = cmudict.dict(); HY = pyphen.Pyphen(lang="en_GB")
V = {"AA": "ɑ", "AE": "æ", "AH": "ʌ", "AO": "ɔ", "AW": "aʊ", "AY": "aɪ", "EH": "ɛ", "ER": "ɝ", "EY": "eɪ", "IH": "ɪ", "IY": "i", "OW": "oʊ", "OY": "ɔɪ", "UH": "ʊ", "UW": "u"}
C = {"B": "b", "CH": "tʃ", "D": "d", "DH": "ð", "F": "f", "G": "ɡ", "HH": "h", "JH": "dʒ", "K": "k", "L": "l", "M": "m", "N": "n", "NG": "ŋ", "P": "p", "R": "r", "S": "s", "SH": "ʃ", "T": "t", "TH": "θ", "V": "v", "W": "w", "Y": "j", "Z": "z", "ZH": "ʒ"}
ONSETS = set("pl pr bl br tr dr kl kr ɡl ɡr fl fr θr ʃr sp st sk sm sn sl sw spl spr str skr kj pj bj fj mj hj vj tw kw dw ɡw θw sw skw".split()) | set(C.values())
def ipa(word):
    out = []
    for w in word.lower().split():
        p = CMU.get(w)
        if not p: return None
        ph = p[0]; seg = []
        nvow = sum(1 for x in ph if x[-1].isdigit())
        for i, x in enumerate(ph):
            if x[-1].isdigit():
                base, st = x[:-1], x[-1]
                sym = ("ə" if base == "AH" else "ɚ" if base == "ER" else V[base]) if st == "0" else V[base]
                if st == "1" and nvow > 1:
                    # maximal onset: move the stress mark back over consonants that can start a syllable together
                    k = len(seg)
                    while k > 0 and seg[k - 1] in C.values(): k -= 1
                    cons = seg[k:]
                    while cons and "".join(cons) not in ONSETS and len(cons) > 1: cons = cons[1:]; k += 1
                    if cons and len(cons) == 1 and k == 0: pass
                    seg.insert(len(seg) - len(cons), "ˈ")
                seg.append(sym)
            else: seg.append(C[x])
        out.append("".join(seg))
    return "/" + " ".join(out) + "/"
def syll(word):
    n = sum(1 for x in CMU.get(word.lower().split()[0], [[]])[0] if x[-1].isdigit()) if " " not in word else None
    h = HY.inserted(word).replace("-", "·")
    return n, h
words = [v["word"] for v in json.load(open("deliverables/phase-1-content/_work/baseline.json"))["vocabulary"]]
rows = {}
for w in words:
    i = ipa(w); n, h = syll(w)
    rows[w] = {"ipa": i, "syllables": h if (n is None or h.count("·") + 1 == n) else None, "syllable_count": n}
missing = [w for w, r in rows.items() if not r["ipa"]]
open("src/server/content/pronunciation.ts", "w").write(
    "/** Generated by scripts/cambridge/pronunciation.py — IPA from the CMU Pronouncing Dictionary (US English), syllable breaks from en_GB hyphenation\n"
    " * (kept only when they agree with the CMU syllable count). Words not in CMU have no IPA (never invented). */\n"
    "export const PRONUNCIATION: Record<string, { ipa: string | null; syllables: string | null; syllable_count: number | null }> = " + json.dumps(rows, ensure_ascii=False, indent=1) + ";\n")
print(len(rows), "missing IPA:", missing, "| no syllable split:", sum(1 for r in rows.values() if not r["syllables"]))
print({w: rows[w] for w in ["enormous", "apple", "beautiful", "cat", "curious"] if w in rows})
